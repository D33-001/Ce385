// ตัวแปรข้อมูลจำลองในระบบ (ในโลกจริงจะดึงจาก Database)
const VALID_USER = "admin";
const VALID_PASS = "ce385pass";

// ส่วนที่ 1 — ฟังก์ชันตรวจสอบสิทธิ์
function login(inputUser, inputPass, role, isActive, age) {
  // ตรวจสอบ Username หรือ Password ว่าผิดหรือไม่ (ใช้ || หรือ)
  // หากเข้าเงื่อนไขนี้ จะเทียบเท่ากับ HTTP Status 401 Unauthorized (ไม่รู้ว่าคุณคือใคร)
  if (inputUser !== VALID_USER || inputPass !== VALID_PASS) {
    return "ชื่อผู้ใช้หรือรหัสผ่านไม่ถูกต้อง"; 
  }

  // ตรวจสอบสถานะบัญชีถูกระงับ
  // หากเข้าเงื่อนไขนี้ จะเทียบเท่ากับ HTTP Status 403 Forbidden (รู้ว่าคือใคร แต่ห้ามเข้า)
  if (isActive === false) { 
    return "บัญชีนี้ถูกระงับการใช้งาน"; 
  }

  // ตรวจสอบอายุ
  if (age < 18) {
    return "อายุไม่ถึงเกณฑ์";
  }

  // ตรวจสอบ Role (บทบาท)
  // ถึงบรรทัดนี้แปลว่า รหัสถูก บัญชีปกติ และอายุถึงเกณฑ์แล้ว (เทียบเท่า 200 OK)
  if (role === "อาจารย์") {
    return "เข้าสู่ระบบสำเร็จ (สิทธิ์ผู้ดูแล)";
  } else if (role === "นักศึกษา") {
    return "เข้าสู่ระบบสำเร็จ (สิทธิ์ทั่วไป)";
  } else {
    // กฎของ Backend: ต้องดักจับข้อมูลแปลกปลอมเสมอ เผื่อไคลเอนต์ส่ง role อื่นมา
    return "ไม่มีสิทธิ์เข้าถึงระบบ";
  }
}

// ส่วนที่ 2 — ทดสอบการทำงาน 6 กรณี
console.log("===== ผลการทดสอบระบบ Login =====");
// 1. สำเร็จ (อาจารย์) - ข้อมูลถูกต้องทั้งหมด
console.log("1:", login("admin", "ce385pass", "อาจารย์", true, 30));

// 2. สำเร็จ (นักศึกษา) - ข้อมูลถูกต้องทั้งหมด
console.log("2:", login("admin", "ce385pass", "นักศึกษา", true, 20));

// 3. รหัสผ่านผิด (รหัสผิด แต่ข้อมูลอื่นถูก)
console.log("3:", login("admin", "wrongpass", "อาจารย์", true, 30));

// 4. ชื่อผู้ใช้ผิด (ชื่อผิด แต่ข้อมูลอื่นถูก)
console.log("4:", login("wronguser", "ce385pass", "นักศึกษา", true, 20));

// 5. บัญชีถูกระงับ (รหัสถูก แต่อยู่ในสถานะระงับ)
console.log("5:", login("admin", "ce385pass", "นักศึกษา", false, 20));

// 6. อายุไม่ถึง (รหัสถูก แต่ส่วนอายุต่ำกว่า 18)
console.log("6:", login("admin", "ce385pass", "นักศึกษา", true, 15));

